"""Bounded native disk inventory. Every observed native file is retained.

Location categories describe where bytes were observed, never who created
them or whether they are disposable. No file content is opened by this module.
"""
from __future__ import annotations

import math
import os

from . import __version__, disk, schema

DEFAULT_MAX_ENTRIES = 20_000
DEFAULT_MAX_DEPTH = 12
MAX_ROOTS = 12
DEFAULT_MIN_FREE_BYTES = 20 * 1024 ** 3
DEFAULT_MIN_FREE_PERCENT = 10.0

# These are locations, not deletion allowlists or reliable producer ownership.
_LOCATIONS = (
    (".ao/data/worktrees", "worktrees"),
    (".claude/projects", "sessions"),
    (".codex/sessions", "sessions"),
    (".gemini/tmp", "agent-data"),
    (".cache", "shared-caches"),
    (".npm/_cacache", "shared-caches"),
    ("Library/Caches", "shared-caches"),
    ("Projects", "projects"),
)


def _check_thresholds(min_free_bytes, min_free_percent):
    if type(min_free_bytes) is not int or not 0 <= min_free_bytes <= 1024 ** 5:
        raise schema.ValidationError(["min-free-bytes must be an integer between 0 and one PiB"])
    if (isinstance(min_free_percent, bool)
            or not isinstance(min_free_percent, (int, float))
            or not math.isfinite(min_free_percent)
            or not 0 <= min_free_percent <= 100):
        raise schema.ValidationError(["min-free-percent must be finite and between 0 and 100"])


def _volume(path, min_free_bytes, min_free_percent):
    observed = disk.volume_usage(path)
    total = observed["total_bytes"]
    available = observed["available_bytes"]
    percent = 100.0 * available / total if total > 0 else None
    low = (available < min_free_bytes or percent is None
           or percent < min_free_percent)
    return dict(observed, path=path, available_percent=percent,
                pressure="unknown" if percent is None else "low" if low else "normal")


def pressure(path=None, *, min_free_bytes=DEFAULT_MIN_FREE_BYTES,
             min_free_percent=DEFAULT_MIN_FREE_PERCENT, public=False):
    """Read one volume's current capacity without walking any directory."""
    _check_thresholds(min_free_bytes, min_free_percent)
    selected = os.path.abspath(os.path.expanduser(os.fspath(path or os.path.expanduser("~"))))
    data = {
        "schema": "agent-pooper-scooper/host-pressure", "schema_version": 1,
        "version": __version__, "observed_at": schema.format_timestamp(),
        "mode": "observe-only",
        "thresholds": {"min_free_bytes": min_free_bytes, "min_free_percent": min_free_percent},
        "volumes": [], "unknowns": [], "removed_bytes": 0, "reclaimed_bytes": None,
    }
    try:
        data["volumes"].append(_volume(selected, min_free_bytes, min_free_percent))
    except OSError:
        data["unknowns"].append({"path": selected, "reason": "volume_unreadable"})
    data["complete"] = not data["unknowns"]
    return public_view(data) if public else data


def _roots(roots, home):
    known = [(os.path.join(home, relative), category) for relative, category in _LOCATIONS]
    if roots is None:
        # lexists records a symlink as a refused root instead of silently
        # treating its target as an enrolled location.
        return [(path, category) for path, category in known if os.path.lexists(path)]
    supplied = list(roots)
    if not supplied or len(supplied) > MAX_ROOTS:
        raise schema.ValidationError([f"select between 1 and {MAX_ROOTS} roots"])
    selected, seen = [], set()
    for value in supplied:
        path = os.path.abspath(os.path.expanduser(os.fspath(value)))
        if path in (os.path.abspath(os.sep), home):
            raise schema.ValidationError(["select specific directories, not a whole home or filesystem"])
        if path in seen:
            continue
        seen.add(path)
        category = next((kind for base, kind in known
                         if path == base or path.startswith(base + os.sep)), "native-data")
        selected.append((path, category))
    return selected


def scan(roots=None, *, max_entries=DEFAULT_MAX_ENTRIES, max_depth=DEFAULT_MAX_DEPTH,
         min_free_bytes=DEFAULT_MIN_FREE_BYTES, min_free_percent=DEFAULT_MIN_FREE_PERCENT,
         public=False):
    """Measure selected roots, deduplicating hardlinks and overlapping walks.

    Byte counts are measured lower bounds when traversal is incomplete. They
    are neither task-generated bytes nor cleanup candidates. All native data
    stays outside managed collection.
    """
    if type(max_entries) is not int or not 1 <= max_entries <= 100_000:
        raise schema.ValidationError(["max-entries must be between 1 and 100000 per root"])
    if type(max_depth) is not int or not 0 <= max_depth <= 64:
        raise schema.ValidationError(["max-depth must be between 0 and 64"])
    _check_thresholds(min_free_bytes, min_free_percent)
    home = os.path.abspath(os.path.expanduser("~"))
    selected = _roots(roots, home)
    data = {
        "schema": "agent-pooper-scooper/host-inventory", "schema_version": 1,
        "version": __version__, "observed_at": schema.format_timestamp(),
        "mode": "observe-only", "scope": "selected-native-locations",
        "limits": {"max_entries_per_root": max_entries, "max_depth": max_depth,
                   "max_roots": MAX_ROOTS},
        "thresholds": {"min_free_bytes": min_free_bytes, "min_free_percent": min_free_percent},
        "roots": [], "volumes": [], "unknowns": [],
        "totals": {"files": 0, "apparent_bytes": 0, "allocated_bytes": 0,
                   "duplicates": 0, "removed_bytes": 0, "reclaimed_bytes": None},
        "task_attribution": "unknown", "cleanup_authority": "none",
    }
    seen, volumes_seen = set(), set()
    for path, category in selected:
        usage = disk.walk_usage(path, seen=seen, max_entries=max_entries, max_depth=max_depth)
        item = {"path": path, "category": category, "classification_basis": "location-only",
                "decision": "KEEP", "reason": "unmanaged_native_data", "usage": usage.as_dict()}
        data["roots"].append(item)
        for name in ("files", "apparent_bytes", "allocated_bytes", "duplicates"):
            data["totals"][name] += getattr(usage, name)
        if usage.root_status != "measured":
            continue
        try:
            volume = _volume(path, min_free_bytes, min_free_percent)
        except OSError:
            data["unknowns"].append({"path": path, "reason": "volume_unreadable"})
        else:
            if volume["device"] not in volumes_seen:
                volumes_seen.add(volume["device"])
                data["volumes"].append(volume)
    if not selected:
        # A first installation with no recognized roots still reports pressure.
        capacity = pressure(home, min_free_bytes=min_free_bytes,
                            min_free_percent=min_free_percent)
        data["volumes"] = capacity["volumes"]
        data["unknowns"].extend(capacity["unknowns"])
    # A skipped symlink/mount has deliberately unmeasured target contents.
    data["complete"] = not data["unknowns"] and all(
        r["usage"]["root_status"] == "measured" and r["usage"]["complete"]
        and not r["usage"]["skipped_by_reason"] for r in data["roots"])
    data["totals"]["measurement"] = "complete-selected-scope" if data["complete"] else "known-lower-bound"
    return public_view(data) if public else data


def public_view(data):
    """Whitelist summary fields; never project native paths or file details."""
    result = {key: data[key] for key in ("schema", "schema_version", "version", "observed_at",
                                       "mode", "thresholds", "complete")}
    result["volumes"] = [
        dict({key: value[key] for key in ("total_bytes", "free_bytes", "available_bytes",
                                        "available_percent", "pressure")}, volume=index)
        for index, value in enumerate(data["volumes"], 1)
    ]
    result["unknown_count"] = len(data["unknowns"]) + sum(
        sum(root["usage"]["unknowns_by_reason"].values()) for root in data.get("roots", []))
    if "roots" in data:
        result.update(scope=data["scope"], limits=dict(data["limits"]),
                      totals=dict(data["totals"]), task_attribution="unknown", cleanup_authority="none")
        result["roots"] = []
        for index, root in enumerate(data["roots"], 1):
            usage = root["usage"]
            summary = {key: usage[key] for key in ("root_status", "allocated_bytes", "apparent_bytes",
                       "files", "directories", "duplicates", "complete", "skipped_by_reason", "unknowns_by_reason")}
            result["roots"].append({"bucket": index, "decision": "KEEP", "usage": summary})
    else:
        result.update(removed_bytes=0, reclaimed_bytes=None)
    return result


def _size(value):
    amount = float(value)
    for unit in ("B", "KiB", "MiB", "GiB", "TiB", "PiB"):
        if abs(amount) < 1024 or unit == "PiB":
            return f"{amount:.1f} {unit}"
        amount /= 1024


def _cell(value):
    # Native filenames remain data in Markdown, including pipes and line breaks.
    return (str(value).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace("\\", "\\\\").replace("|", "\\|").replace("\r", " ").replace("\n", " ")
            .replace("`", "\\`").replace("[", "\\[").replace("]", "\\]"))


def render_markdown(data):
    lines = ["# Agent Pooper Scooper — disk report", "", f"Observed: {data['observed_at']}", "",
             "Mode: **observe-only**. Existing native files are retained.", ""]
    for index, volume in enumerate(data["volumes"], 1):
        percent = volume["available_percent"]
        percentage = "unknown" if percent is None else f"{percent:.1f}%"
        lines.append(f"Volume {index}: **{_size(volume['available_bytes'])} available** ({percentage}); "
                     f"pressure: **{volume['pressure']}**.")
    if not data["volumes"]:
        lines.append("Volume availability: unknown.")
    if "roots" in data:
        lines.extend(["", "| Location | Files | Apparent size | Allocated size | Status |",
                      "| --- | ---: | ---: | ---: | --- |"])
        for index, root in enumerate(data["roots"], 1):
            usage = root["usage"]
            label = _cell(root.get("path", f"Bucket {index}"))
            status = "measured" if (usage["complete"] and usage["root_status"] == "measured"
                      and not usage["skipped_by_reason"]) else "partial / skipped"
            lines.append(f"| {label} | {usage['files']} | {_size(usage['apparent_bytes'])} | "
                         f"{_size(usage['allocated_bytes'])} | {status}; KEEP |")
        totals = data["totals"]
        lines.extend(["", f"Measured total: **{_size(totals['apparent_bytes'])}** in **{totals['files']} regular files**.",
                      "Totals deduplicate observed hardlinks and overlapping walks. Partial totals are lower bounds.",
                      "Location is not proof of task ownership or disposability. No cleanup candidates are authorized."])
    lines.extend(["", "Files removed: **0 bytes**. Actual reclaimed capacity: **unknown**.",
                  "Allocated and apparent sizes do not establish reclaimable space; APFS clones, snapshots and open files can retain blocks.", ""])
    return "\n".join(lines)
